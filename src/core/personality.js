// Проверка: сейчас среда? (по часовому поясу Екатеринбурга UTC+5)
function isWednesday() {
    const now = new Date();
    const ekbDay = new Date(now.toLocaleString("en-US", { timeZone: "Asia/Yekaterinburg" }));
    return ekbDay.getDay() === 3; // 0=Вс, 1=Пн, 2=Вт, 3=Ср, 4=Чт, 5=Пт, 6=Сб
}

